/**
 * A MySQL physical column type with an explicit scalar transport mapping.
 *
 * Values remain bound parameters. Factories in [MySqlTypes] validate type parameters
 * before an SQL declaration reaches the renderer.
 */
class MySqlColumnType<T : Any, S : Any> internal constructor(
    name: String,
    storageType: ColumnType<S>,
    mapping: ColumnMapping<T, S>,
    /** SQL declaration generated by a validated [MySqlTypes] factory. */
    val sqlDeclaration: String,
    /** Whether MariaDB may reuse this physical declaration without changing its semantics. */
    val isMariaDbCompatible: Boolean = true,
) : ScalarMappedColumnType<T, S>(name, storageType, mapping),
    StableSchemaColumnType {
    override val schemaTypeDescriptor = SchemaTypeDescriptor(
        id = "kagiroi.mysql.declared",
        arguments = listOf(SchemaTypeArgument("declaration", sqlDeclaration)),
    )
}

/** MySQL 8.4 physical column type factories. */
@Suppress("TooManyFunctions") // Mirrors the public MySQL data type catalog.
object MySqlTypes {
    val boolean: MySqlColumnType<Boolean, Boolean> = scalar("MySQL BOOLEAN", BooleanColumnType, "BOOLEAN")
    val tinyInt: MySqlColumnType<Byte, Byte> = scalar("MySQL TINYINT", ByteColumnType, "TINYINT")
    val tinyIntUnsigned: MySqlColumnType<UByte, UByte> = scalar(
        "MySQL TINYINT UNSIGNED",
        UByteColumnType,
        "TINYINT UNSIGNED",
    )
    val smallInt: MySqlColumnType<Short, Short> = scalar("MySQL SMALLINT", ShortColumnType, "SMALLINT")
    val smallIntUnsigned: MySqlColumnType<UShort, UShort> = scalar(
        "MySQL SMALLINT UNSIGNED",
        UShortColumnType,
        "SMALLINT UNSIGNED",
    )
    val mediumInt: MySqlColumnType<Int, Int> = scalar("MySQL MEDIUMINT", IntColumnType, "MEDIUMINT")
    val mediumIntUnsigned: MySqlColumnType<UInt, UInt> = scalar(
        "MySQL MEDIUMINT UNSIGNED",
        UIntColumnType,
        "MEDIUMINT UNSIGNED",
    )
    val integer: MySqlColumnType<Int, Int> = scalar("MySQL INT", IntColumnType, "INT")
    val integerUnsigned: MySqlColumnType<UInt, UInt> = scalar("MySQL INT UNSIGNED", UIntColumnType, "INT UNSIGNED")
    val bigInt: MySqlColumnType<Long, Long> = scalar("MySQL BIGINT", LongColumnType, "BIGINT")
    val bigIntUnsigned: MySqlColumnType<ULong, ULong> = scalar(
        "MySQL BIGINT UNSIGNED",
        ULongColumnType,
        "BIGINT UNSIGNED",
    )

    /** MySQL `SERIAL` is its own BIGINT UNSIGNED AUTO_INCREMENT UNIQUE shorthand. */
    val serial: MySqlColumnType<ULong, ULong> = scalar("MySQL SERIAL", ULongColumnType, "SERIAL")
    val float: MySqlColumnType<Float, Float> = scalar("MySQL FLOAT", FloatColumnType, "FLOAT")
    val double: MySqlColumnType<Double, Double> = scalar("MySQL DOUBLE", DoubleColumnType, "DOUBLE")
    val year: MySqlColumnType<Int, Int> = scalar("MySQL YEAR", IntColumnType, "YEAR")

    val tinyText: MySqlColumnType<String, String> = text("TINYTEXT")
    val text: MySqlColumnType<String, String> = text("TEXT")
    val mediumText: MySqlColumnType<String, String> = text("MEDIUMTEXT")
    val longText: MySqlColumnType<String, String> = text("LONGTEXT")
    val tinyBlob: MySqlColumnType<ByteArray, ByteArray> = bytes("TINYBLOB")
    val blob: MySqlColumnType<ByteArray, ByteArray> = bytes("BLOB")
    val mediumBlob: MySqlColumnType<ByteArray, ByteArray> = bytes("MEDIUMBLOB")
    val longBlob: MySqlColumnType<ByteArray, ByteArray> = bytes("LONGBLOB")

    /** A UUID stored in a portable MySQL-compatible `CHAR(36)` column. */
    val charUuid: MySqlColumnType<Uuid, String> = MySqlColumnType(
        name = "MySQL-compatible CHAR(36) UUID",
        storageType = StringColumnType,
        mapping = columnMapping(fromStorage = Uuid::parse, toStorage = Uuid::toString),
        sqlDeclaration = "CHAR(36)",
    )

    /**
     * A UUID stored in a MySQL-compatible `BINARY(16)` column.
     *
     * The bytes use the UUID RFC 4122 network-byte-order representation; this does not
     * apply MySQL's optional time-part byte swapping convention.
     */
    val binaryUuid: MySqlColumnType<Uuid, ByteArray> = MySqlColumnType(
        name = "MySQL-compatible BINARY(16) UUID",
        storageType = ByteArrayColumnType,
        mapping = columnMapping(
            fromStorage = ByteArray::toMySqlBinaryUuid,
            toStorage = Uuid::toMySqlBinaryUuid,
        ),
        sqlDeclaration = "BINARY(16)",
    )

    val json: MySqlColumnType<String, String> = MySqlColumnType(
        name = "MySQL JSON",
        storageType = StringColumnType,
        mapping = columnMapping(fromStorage = { it }, toStorage = { it }),
        sqlDeclaration = "JSON",
        isMariaDbCompatible = false,
    )

    /**
     * MySQL geometry values use the server's binary parameter format: a little-endian
     * four-byte SRID followed by WKB. The shared mysql2 adapters preserve those bytes
     * rather than materializing JavaScript geometry objects.
     */
    val geometry: MySqlColumnType<ByteArray, ByteArray> = bytes("GEOMETRY")
    val point: MySqlColumnType<ByteArray, ByteArray> = bytes("POINT")
    val lineString: MySqlColumnType<ByteArray, ByteArray> = bytes("LINESTRING")
    val polygon: MySqlColumnType<ByteArray, ByteArray> = bytes("POLYGON")
    val multiPoint: MySqlColumnType<ByteArray, ByteArray> = bytes("MULTIPOINT")
    val multiLineString: MySqlColumnType<ByteArray, ByteArray> = bytes("MULTILINESTRING")
    val multiPolygon: MySqlColumnType<ByteArray, ByteArray> = bytes("MULTIPOLYGON")
    val geometryCollection: MySqlColumnType<ByteArray, ByteArray> = bytes("GEOMETRYCOLLECTION")

    fun bit(length: Int): MySqlColumnType<ByteArray, ByteArray> = bytes("BIT(${positive(length, "length")})")

    fun decimal(precision: Int, scale: Int): MySqlColumnType<String, String> {
        require(precision in 1..MYSQL_MAX_DECIMAL_PRECISION) {
            "MySQL DECIMAL precision must be between 1 and $MYSQL_MAX_DECIMAL_PRECISION: $precision"
        }
        require(scale in 0..minOf(precision, MYSQL_MAX_DECIMAL_SCALE)) {
            "MySQL DECIMAL scale must be between 0 and ${minOf(precision, MYSQL_MAX_DECIMAL_SCALE)}: $scale"
        }
        return text("DECIMAL($precision,$scale)")
    }

    /** `NUMERIC` is a MySQL synonym for `DECIMAL` with the same precision rules. */
    fun numeric(precision: Int, scale: Int): MySqlColumnType<String, String> = decimal(precision, scale)

    /** Creates a constrained DECIMAL declaration with an explicit lossless application mapping. */
    fun <T : Any> decimal(precision: Int, scale: Int, mapping: ColumnMapping<T, String>): MySqlColumnType<T, String> =
        mappedText(decimal(precision, scale).sqlDeclaration, mapping)

    /** Creates a constrained NUMERIC declaration with an explicit lossless application mapping. */
    fun <T : Any> numeric(precision: Int, scale: Int, mapping: ColumnMapping<T, String>): MySqlColumnType<T, String> =
        decimal(precision, scale, mapping)

    /** `DATE` with its raw textual transport. */
    fun date(): MySqlColumnType<String, String> = text("DATE")

    /**
     * `DATE` with an explicit application mapping over its textual transport.
     *
     * The mapping owns parsing and validation; this factory does not infer a time zone
     * or accept non-text driver values on the application's behalf.
     */
    fun <T : Any> date(mapping: ColumnMapping<T, String>): MySqlColumnType<T, String> =
        mappedText(date().sqlDeclaration, mapping)

    /** `TIME` with its raw textual transport. */
    fun time(fractionalSecondsPrecision: Int = 0): MySqlColumnType<String, String> =
        text("TIME${fractionalSeconds(fractionalSecondsPrecision)}")

    /** `TIME(fsp)` with an explicit application mapping over its textual transport. */
    fun <T : Any> time(
        fractionalSecondsPrecision: Int,
        mapping: ColumnMapping<T, String>,
    ): MySqlColumnType<T, String> = mappedText(time(fractionalSecondsPrecision).sqlDeclaration, mapping)

    /** `DATETIME` with its raw textual transport. */
    fun dateTime(fractionalSecondsPrecision: Int = 0): MySqlColumnType<String, String> =
        text("DATETIME${fractionalSeconds(fractionalSecondsPrecision)}")

    /** `DATETIME(fsp)` with an explicit application mapping over its textual transport. */
    fun <T : Any> dateTime(
        fractionalSecondsPrecision: Int,
        mapping: ColumnMapping<T, String>,
    ): MySqlColumnType<T, String> = mappedText(dateTime(fractionalSecondsPrecision).sqlDeclaration, mapping)

    /**
     * `TIMESTAMP` deliberately retains raw textual transport.
     *
     * Its session-time-zone conversion semantics are not equivalent to a local civil
     * date-time mapping.
     */
    fun timestamp(fractionalSecondsPrecision: Int = 0): MySqlColumnType<String, String> =
        text("TIMESTAMP${fractionalSeconds(fractionalSecondsPrecision)}")

    fun char(length: Int): MySqlColumnType<String, String> = text("CHAR(${positive(length, "length")})")

    fun varchar(maxLength: Int): MySqlColumnType<String, String> = text("VARCHAR(${positive(maxLength, "maxLength")})")

    fun binary(length: Int): MySqlColumnType<ByteArray, ByteArray> = bytes("BINARY(${positive(length, "length")})")

    fun varbinary(maxLength: Int): MySqlColumnType<ByteArray, ByteArray> =
        bytes("VARBINARY(${positive(maxLength, "maxLength")})")

    /**
     * Represents a declared MySQL ENUM type as its selected label.
     *
     * The factory deliberately accepts only labels representable independently of
     * `NO_BACKSLASH_ESCAPES`; labels outside that portable literal subset need
     * application-owned vendor DDL.
     */
    fun enum(first: String, vararg remaining: String): MySqlColumnType<String, String> =
        enum(nonEmptyListOf(first, *remaining))

    fun enum(labels: NonEmptyList<String>): MySqlColumnType<String, String> =
        text("ENUM(${labels.renderMySqlLabels("ENUM")})")

    /** Represents a declared MySQL SET type as its server text representation. */
    fun set(first: String, vararg remaining: String): MySqlColumnType<String, String> =
        set(nonEmptyListOf(first, *remaining))

    fun set(labels: NonEmptyList<String>): MySqlColumnType<String, String> =
        text("SET(${labels.renderMySqlLabels("SET")})")

    private fun text(declaration: String): MySqlColumnType<String, String> =
        scalar("MySQL $declaration", StringColumnType, declaration)

    private fun <T : Any> mappedText(
        declaration: String,
        mapping: ColumnMapping<T, String>,
    ): MySqlColumnType<T, String> = MySqlColumnType(
        name = "MySQL $declaration",
        storageType = StringColumnType,
        mapping = mapping,
        sqlDeclaration = declaration,
    )

    private fun bytes(declaration: String): MySqlColumnType<ByteArray, ByteArray> =
        scalar("MySQL $declaration", ByteArrayColumnType, declaration)

    private fun <T : Any> scalar(
        name: String,
        storageType: ColumnType<T>,
        declaration: String,
    ): MySqlColumnType<T, T> = MySqlColumnType(
        name = name,
        storageType = storageType,
        mapping = columnMapping(fromStorage = { it }, toStorage = { it }),
        sqlDeclaration = declaration,
    )

    private fun positive(value: Int, parameter: String): Int {
        require(value > 0) { "MySQL $parameter must be positive: $value" }
        return value
    }

    private fun fractionalSeconds(precision: Int): String {
        require(precision in 0..MAX_FRACTIONAL_SECONDS_PRECISION) {
            "MySQL fractional seconds precision must be between 0 and $MAX_FRACTIONAL_SECONDS_PRECISION: $precision"
        }
        return "($precision)"
    }
}

private fun NonEmptyList<String>.renderMySqlLabels(typeName: String): String {
    require(distinct().size == size) { "MySQL $typeName labels must be distinct" }
    return joinToString(",") { label ->
        require(label.none { it == '\\' || it == '\u0000' }) {
            "MySQL $typeName labels containing backslashes or NUL require explicit vendor DDL"
        }
        "'${label.replace("'", "''")}'"
    }
}

internal fun Uuid.toMySqlBinaryUuid(): ByteArray {
    val hexadecimal = toString().filterNot { it == '-' }
    return ByteArray(UUID_BYTE_COUNT) { index ->
        hexadecimal.substring(index * UUID_HEX_BYTE_WIDTH, index * UUID_HEX_BYTE_WIDTH + UUID_HEX_BYTE_WIDTH)
            .toInt(UUID_HEX_RADIX)
            .toByte()
    }
}

internal fun ByteArray.toMySqlBinaryUuid(): Uuid {
    require(size == UUID_BYTE_COUNT) { "MySQL binary UUID must contain 16 bytes" }
    val hexadecimal = joinToString("") { byte ->
        (byte.toInt() and UUID_BYTE_MASK).toString(UUID_HEX_RADIX).padStart(2, '0')
    }
    return Uuid.parse(
        buildString(UUID_TEXT_LENGTH) {
            append(hexadecimal, UUID_HEX_START, UUID_TIME_LOW_END)
            append('-')
            append(hexadecimal, UUID_TIME_LOW_END, UUID_TIME_MID_END)
            append('-')
            append(hexadecimal, UUID_TIME_MID_END, UUID_VERSION_END)
            append('-')
            append(hexadecimal, UUID_VERSION_END, UUID_VARIANT_END)
            append('-')
            append(hexadecimal, UUID_VARIANT_END, UUID_HEX_END)
        },
    )
}

private const val MYSQL_MAX_DECIMAL_PRECISION = 65
private const val MYSQL_MAX_DECIMAL_SCALE = 30
private const val MAX_FRACTIONAL_SECONDS_PRECISION = 6
private const val UUID_BYTE_COUNT = 16
private const val UUID_TEXT_LENGTH = 36
private const val UUID_HEX_START = 0
private const val UUID_TIME_LOW_END = 8
private const val UUID_TIME_MID_END = 12
private const val UUID_VERSION_END = 16
private const val UUID_VARIANT_END = 20
private const val UUID_HEX_END = 32
private const val UUID_HEX_BYTE_WIDTH = 2
private const val UUID_HEX_RADIX = 16
private const val UUID_BYTE_MASK = 0xff
